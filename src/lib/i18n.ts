/**
 * Merge the editorial copy deck (src/lib/i18nCopy.ts) over the base dictionary
 * for each language. Nested sections merge key by key, so the deck can add new
 * strings and re-voice individual existing ones without restating a section.
 */
function deepMerge(base: Dictionary, override: Dictionary): Dictionary {
  const result: Dictionary = { ...base };
  for (const [key, value] of Object.entries(override)) {
    const existing = result[key];
    if (
      value && typeof value === 'object' &&
      existing && typeof existing === 'object'
    ) {
      result[key] = deepMerge(existing, value);
    } else {
      result[key] = value;
    }
  }
  return result;
}

for (const code of Object.keys(translations) as AppLanguageCode[]) {
  translations[code] = deepMerge(translations[code], editorialCopy[code] as Dictionary);
}

function resolveKey(dictionary: Dictionary, path: string): string | null {
  const parts = path.split('.');
  let current: string | Dictionary = dictionary;
  for (const part of parts) {
    if (typeof current !== 'object' || current == null) return null;
    const next: string | Dictionary | undefined = (current as Dictionary)[part];
    if (next == null) return null;
    current = next;
  }
  return typeof current === 'string' ? current : null;
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    const value = params[key];
    return value == null ? '' : String(value);
  });
}

export function useI18n() {
  const language = usePreferencesStore((s) => s.language);
  const locale = LOCALE_MAP[language] ?? 'en-US';

  const t = useMemo(() => {
    return (key: string, params?: Record<string, string | number>) => {
      const primary = resolveKey(translations[language], key);
      const fallback = resolveKey(translations.en, key);
      const template = primary ?? fallback ?? key;
      return interpolate(template, params);
    };
  }, [language]);

  const tCount = useMemo(() => {
    const rules = new Intl.PluralRules(locale);
    return (key: string, count: number, params?: Record<string, string | number>) => {
      const form = rules.select(count);
      const primary = resolveKey(translations[language], `${key}.${form}`)
        ?? resolveKey(translations[language], `${key}.other`);
      const fallback = resolveKey(translations.en, `${key}.${form}`)
        ?? resolveKey(translations.en, `${key}.other`);
      const template = primary ?? fallback ?? key;
      return interpolate(template, { count, ...params });
    };
  }, [language, locale]);

  const formatCurrency = useMemo(() => {
    return (value: number) =>
      new Intl.NumberFormat(locale, {
        style: 'currency',
        currency: 'USD',
        maximumFractionDigits: 2,
      }).format(value);
  }, [locale]);

  const formatDate = useMemo(() => {
    return (value: Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(locale, options ?? {
        year: 'numeric',
        month: 'short',
        day: 'numeric',
      }).format(value);
  }, [locale]);

  const formatDateTime = useMemo(() => {
    return (value: Date) =>
      new Intl.DateTimeFormat(locale, {
        year: 'numeric',
        month: 'short',
        day: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
      }).format(value);
  }, [locale]);

  return {
    t,
    tCount,
    locale,
    formatCurrency,
    formatDate,
    formatDateTime,
  };
}
